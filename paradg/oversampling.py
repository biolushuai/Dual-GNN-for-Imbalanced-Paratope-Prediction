"""Structure-preserving graph oversampling (Algorithm 1 of the manuscript).

Synthetic minority (paratope) nodes are generated by interpolating a paratope
residue with one of its k nearest paratope neighbours in *embedding space*.
Every synthetic node inherits the graph neighbourhood and the surface label of
its parent, so the augmented graph keeps the native spatial connectivity
instead of attaching random edges.

The kNN search uses Euclidean distance over residue embeddings, as stated in
Section II-D-2 of the manuscript.
"""

from __future__ import annotations

import math
from typing import List, Optional, Sequence

import torch
from torch_geometric.data import Data


class StructurePreservingGraphOversampler:
    """Balance an antibody graph by replicating paratope neighbourhood structure.

    Args:
        k_neighbors: Number of nearest paratope neighbours considered per parent.
        target_pos_ratio: Desired positive ratio used by Algorithm 1 (default 0.5).
        sample_ratio: Alternative specification. When set, the number of synthetic
            nodes is ``ceil(num_pos * (sample_ratio - 1))`` and ``target_pos_ratio``
            is ignored. Useful for the oversampling-ratio ablation (1.0 - 4.0).
        metric: Distance used by the kNN search. ``"euclidean"`` (manuscript) or
            ``"cosine"``.
        synthetic_edges: How synthetic nodes are wired into the graph.
        lambda_max: Upper bound of the interpolation coefficient. Algorithm 1
            draws ``lambda ~ U(0, 1)``, so a synthetic node can land anywhere
            between its parent and its partner -- including the midpoint, which
            in a sparse paratope region is a low-density point that carries a
            positive label it does not deserve. Capping lambda keeps synthetic
            nodes in the high-density shell around a real paratope residue.
            ``lambda_max = 1.0`` reproduces the manuscript exactly.

            ``"bidirectional"``
                Algorithm 1 as printed in the manuscript: the synthetic node both
                receives from and sends to every neighbour of its parent. Because
                Algorithm 1 balances to 50 %, a paratope residue gets ~19.5 copies
                of itself, its in-degree grows 10.1 -> 82.9 and 87 % of its
                incoming edges come from synthetic nodes -- none of which exist at
                inference time. That structural train/inference mismatch is
                amplified by depth and makes training collapse.
            ``"incoming"``
                Synthetic nodes only *receive* from the parent's neighbourhood
                (real -> synthetic) plus a self-loop. They still contribute to the
                loss with a structurally meaningful representation, but they never
                appear in any real node's neighbourhood, so the graph seen by the
                real residues is bit-identical to inference time.
            ``"isolated"``
                Self-loop only: the synthetic node is a pure feature-space sample.
    """

    def __init__(
        self,
        k_neighbors: int = 7,
        target_pos_ratio: float = 0.5,
        sample_ratio: Optional[float] = None,
        metric: str = "euclidean",
        synthetic_edges: str = "bidirectional",
        lambda_max: float = 1.0,
    ):
        if metric not in ("euclidean", "cosine"):
            raise ValueError(f"Unsupported kNN metric: {metric}")
        if not 0.0 < lambda_max <= 1.0:
            raise ValueError(f"lambda_max must be in (0, 1], got {lambda_max}")
        if synthetic_edges not in ("bidirectional", "incoming", "isolated"):
            raise ValueError(f"Unsupported synthetic_edges mode: {synthetic_edges}")
        self.k_neighbors = int(k_neighbors)
        self.target_pos_ratio = float(target_pos_ratio)
        self.sample_ratio = sample_ratio
        self.metric = metric
        self.synthetic_edges = synthetic_edges
        self.lambda_max = float(lambda_max)

    def _num_synthetic(self, num_pos: int, num_total: int) -> int:
        if self.sample_ratio is not None:
            return max(0, math.ceil(num_pos * (self.sample_ratio - 1.0)))
        if num_pos / max(num_total, 1) >= self.target_pos_ratio:
            return 0
        return max(
            0,
            math.ceil(
                (self.target_pos_ratio * num_total - num_pos) / (1.0 - self.target_pos_ratio)
            ),
        )

    def _knn_within_positives(self, pos_features: torch.Tensor) -> torch.Tensor:
        """Return, for each positive node, the indices of its k nearest positives."""
        num_pos = pos_features.size(0)
        k = min(self.k_neighbors, max(num_pos - 1, 1))

        if self.metric == "cosine":
            normalised = torch.nn.functional.normalize(pos_features, dim=-1)
            sim = normalised @ normalised.t()
            dist = 1.0 - sim
        else:
            sq = (pos_features ** 2).sum(-1)
            dist = torch.clamp(sq[:, None] + sq[None, :] - 2 * pos_features @ pos_features.t(), min=0)
            dist = torch.sqrt(dist)

        dist.fill_diagonal_(float("inf"))
        return torch.topk(dist, k=k, largest=False).indices

    def __call__(self, data: Data) -> Data:
        pos_mask = data.y == 1
        num_pos = int(pos_mask.sum())
        num_total = data.y.size(0)
        num_new = self._num_synthetic(num_pos, num_total)

        if num_pos == 0 or num_new == 0:
            # Still publish an (all-False) syn_mask: PyG's collate requires every
            # graph in a batch to carry the same attributes, and a graph whose
            # positive ratio already meets the target simply adds no synthetic
            # nodes. Without this the DataLoader raises KeyError: 'syn_mask'.
            data.syn_mask = torch.zeros(num_total, dtype=torch.bool, device=data.x.device)
            return data

        pos_index = torch.nonzero(pos_mask).squeeze(-1)
        pos_features = data.x[pos_index]
        neighbors = self._knn_within_positives(pos_features)

        global_adj = self._adjacency_dict(data.edge_index, num_total)
        surface_adj = self._adjacency_dict(data.surface_edge_index, num_total)
        surface_flag = (
            data.surface_mask.bool()
            if hasattr(data, "surface_mask") and data.surface_mask is not None
            else torch.ones(num_total, dtype=torch.bool)
        )

        new_features: List[torch.Tensor] = []
        new_global: List[List[int]] = []
        new_surface: List[List[int]] = []
        new_surface_flags: List[bool] = []

        for count in range(num_new):
            parent_slot = count % num_pos
            parent = int(pos_index[parent_slot])
            candidates = neighbors[parent_slot]
            partner = int(candidates[torch.randint(0, candidates.numel(), (1,))])

            # Algorithm 1 draws lambda ~ U(0, 1); lambda_max < 1 caps how far a
            # synthetic node may drift from its parent (see class docstring).
            lam = torch.rand(1, device=data.x.device, dtype=data.x.dtype) * self.lambda_max
            new_features.append((1 - lam) * data.x[parent] + lam * data.x[partner])

            node = num_total + count
            attached = global_adj.get(parent, [])
            if self.synthetic_edges != "isolated":
                # real -> synthetic: gives the synthetic node the parent's context
                for u in attached:
                    new_global.append([u, node])
                if self.synthetic_edges == "bidirectional":
                    # synthetic -> real: this is the direction that perturbs the
                    # neighbourhood the real residues actually see at inference
                    for u in attached:
                        new_global.append([node, u])
            new_global.append([node, node])

            if bool(surface_flag[parent]):
                surf_attached = surface_adj.get(parent, [])
                if self.synthetic_edges != "isolated":
                    for u in surf_attached:
                        new_surface.append([u, node])
                    if self.synthetic_edges == "bidirectional":
                        for u in surf_attached:
                            new_surface.append([node, u])
                new_surface.append([node, node])

            new_surface_flags.append(bool(surface_flag[parent]))

        x = torch.cat([data.x, torch.stack(new_features)], dim=0)
        y = torch.cat([data.y, torch.ones(num_new, dtype=data.y.dtype, device=data.y.device)])
        surface_mask = torch.cat(
            [
                surface_flag,
                torch.tensor(new_surface_flags, dtype=torch.bool, device=data.y.device),
            ]
        )

        out = Data(x=x, y=y, surface_mask=surface_mask, name=getattr(data, "name", ""))
        out.edge_index = self._extend_edges(data.edge_index, new_global)
        out.surface_edge_index = self._extend_edges(data.surface_edge_index, new_surface)
        # Marks which rows of ``y``/``x`` are synthetic so that the training loop can
        # down-weight them (they are interpolated, i.e. noisier than real residues).
        out.syn_mask = torch.cat(
            [
                torch.zeros(num_total, dtype=torch.bool, device=x.device),
                torch.ones(num_new, dtype=torch.bool, device=x.device),
            ]
        )
        return out

    @staticmethod
    def _adjacency_dict(edge_index: torch.Tensor, num_nodes: int) -> dict:
        adj: dict = {i: [] for i in range(num_nodes)}
        if edge_index is None or edge_index.numel() == 0:
            return adj
        src, dst = edge_index[0].tolist(), edge_index[1].tolist()
        for s, d in zip(src, dst):
            if s != d:
                adj.setdefault(s, []).append(d)
        return adj

    @staticmethod
    def _extend_edges(edge_index: torch.Tensor, new_edges: Sequence[Sequence[int]]) -> torch.Tensor:
        if not new_edges:
            return edge_index
        extra = torch.tensor(new_edges, dtype=torch.long, device=edge_index.device).t()
        if edge_index is None or edge_index.numel() == 0:
            return extra
        return torch.cat([edge_index, extra], dim=1)

    def oversample(self, graphs: Sequence[Data]) -> List[Data]:
        """Apply the oversampler to a list of graphs (training split only)."""
        return [self(g) for g in graphs]
